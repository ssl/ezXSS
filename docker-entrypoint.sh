#!/bin/bash
set -euo pipefail

APP_DIR="/var/www/html"
ENV_FILE="${APP_DIR}/.env"

DB_HOST="${DB_HOST:-db}"
DB_PORT="${DB_PORT:-3306}"
DB_NAME="${DB_NAME:-ezxss}"
DB_USER="${DB_USER:-ezxss}"
DB_PASS="${DB_PASS:-}"
DB_CHARSET="${DB_CHARSET:-utf8mb4}"
DOMAIN="${DOMAIN:-localhost}"
TIMEZONE="${TIMEZONE:-UTC}"
DEBUG="${DEBUG:-false}"
VERSION="${VERSION:-5.0}"
IP_LOCK="${IP_LOCK:-false}"
ALLOWED_IPS="${ALLOWED_IPS:-}"
SESSION_TTL="${SESSION_TTL:-604800}"
PANEL_DOMAINS="${PANEL_DOMAINS:-}"
TRUST_PROXY="${TRUST_PROXY:-false}"

generate_env() {
    if [ -f "$ENV_FILE" ]; then
        echo ".env already present — leaving it untouched."
        return
    fi
    echo "Generating .env from container environment (first boot)..."
    mkdir -p "$(dirname "$ENV_FILE")"
    ( umask 027
      cat > "$ENV_FILE" <<EOF
# Generated by docker-entrypoint.sh on first boot. Edit and restart to change.
VERSION=${VERSION}
DEBUG=${DEBUG}
DOMAIN=${DOMAIN}
TIMEZONE=${TIMEZONE}

DB_HOST=${DB_HOST}
DB_PORT=${DB_PORT}
DB_NAME=${DB_NAME}
DB_USER=${DB_USER}
DB_PASS=${DB_PASS}
DB_CHARSET=${DB_CHARSET}

IP_LOCK=${IP_LOCK}
ALLOWED_IPS=${ALLOWED_IPS}

SESSION_TTL=${SESSION_TTL}
PANEL_DOMAINS=${PANEL_DOMAINS}
TRUST_PROXY=${TRUST_PROXY}
EOF
    )
    chown www-data:www-data "$ENV_FILE" 2>/dev/null || true
    echo ".env written (DB host: ${DB_HOST}:${DB_PORT}, db: ${DB_NAME})."
}

wait_for_db() {
    echo "Waiting for database at ${DB_HOST}:${DB_PORT}..."
    local attempts=0
    local max_attempts=60
    until (exec 3<>"/dev/tcp/${DB_HOST}/${DB_PORT}") 2>/dev/null; do
        attempts=$((attempts + 1))
        if [ "$attempts" -ge "$max_attempts" ]; then
            echo "Database did not become reachable after ${max_attempts} tries — continuing anyway."
            echo "The configure screen will explain the DB is unreachable."
            return
        fi
        sleep 2
    done
    echo "Database is accepting connections."
}

obtain_certificate() {
    if [ "${INSTALL_CERTIFICATE:-false}" = "true" ]; then
        if [ ! -e "/etc/letsencrypt/live/${DOMAIN}/fullchain.pem" ]; then
            echo "Attempting to obtain an SSL certificate for ${DOMAIN}..."
            if ! grep -q "ServerName ${DOMAIN}" /etc/apache2/apache2.conf; then
                echo "ServerName ${DOMAIN}" >> /etc/apache2/apache2.conf
            fi
            apache2ctl start || { echo "Failed to start Apache for ACME validation"; exit 1; }
            sleep 5
            if certbot certonly --non-interactive --agree-tos --email "webmaster@${DOMAIN}" \
                --webroot --webroot-path="${APP_DIR}" -d "${DOMAIN}" \
                && [ -e "/etc/letsencrypt/live/${DOMAIN}/fullchain.pem" ]; then
                echo "Certificate obtained. Updating Apache SSL configuration..."
                sed -i "s|SSLCertificateFile .*|SSLCertificateFile /etc/letsencrypt/live/${DOMAIN}/fullchain.pem|g" /etc/apache2/sites-available/default-ssl.conf
                sed -i "s|SSLCertificateKeyFile .*|SSLCertificateKeyFile /etc/letsencrypt/live/${DOMAIN}/privkey.pem|g" /etc/apache2/sites-available/default-ssl.conf
                apache2ctl graceful || { echo "Failed to reload Apache"; exit 1; }
            else
                echo "Certbot failed to obtain the certificate — continuing with the self-signed cert."
            fi
            apache2ctl stop || true
            sleep 2
        else
            echo "SSL certificate already exists for ${DOMAIN}. Skipping acquisition."
        fi
    else
        echo "SSL certificate acquisition not requested (serving the self-signed cert)."
    fi
}

generate_env
wait_for_db
obtain_certificate

echo "Starting Apache in the foreground..."
exec apache2-foreground
